#!/usr/bin/env python3
"""add_annex_noindex.py — keep the historical annexes out of the search index.

Why this exists
---------------
On 2026-11-19 a live audit of the published site (arena/b3ed16c4) found that six
directories in this repository ship their own complete HTML sites next to the
canonical publication at /Zone1/:

    site/  dashboard/  research/  s2/  annex-88769516/  session-3740f69d/

Four of them are generated by scripts that can be edited (scripts/build_site.py,
research/build_research.py, scripts/build_s2_site.py). Three are static: no script
in this repository writes them, so they are repaired here in place, idempotently,
and the same script is safe to re-run.

What it does
------------
* Adds ``<meta name="robots" content="noindex,follow">`` to every page in the three
  static trees that has no robots directive.
* Adds an absolute ``<link rel="canonical">`` pointing at the page's own URL.
* Leaves every other byte of every page untouched. No content, no link, no value
  and no disclosure is altered.

What it deliberately does not do
--------------------------------
It does not delete, hide or 404 the annexes. They are the evidence trail the
publication's own review pages link to, so they must stay reachable. "noindex" is
about not competing with the shop in a search result, not about concealment.

Run:  python3 scripts/add_annex_noindex.py

Exit status is 0 whether or not anything changed, and non-zero only if a tree is
missing or a page cannot be parsed. The build guard in build.py
(check_annex_noindex) is what makes the rule enforceable.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = "https://kanlerxz87-cyber.github.io/Zone1/"

# Trees with no generator in this repository. Each entry is (directory, note).
STATIC_TREES = [
    ("dashboard", "campaign dashboard build"),
    ("annex-88769516", "independent annex build"),
    ("session-3740f69d", "independent session build"),
]

ROBOTS = '<meta name="robots" content="noindex,follow">'
MARKER = "annex-publication-boundary"
COMMENT = (
    "<!-- " + MARKER + " — 2026-11-19, arena/b3ed16c4. Independent verification/history\n"
    "     build, not the canonical publication at /Zone1/. Kept reachable for review and\n"
    "     kept out of the index so one URL set competes for the subject. -->"
)

# Any of these, if already present, means a robots directive exists. A page that already
# says noindex is left alone; a page that says index is repaired, because as of this pass
# no annex tree is meant to be indexed.
HAS_ROBOTS = re.compile(r'<meta\s+name="robots"', re.I)
INDEX_FOLLOW = re.compile(r'<meta\s+name="robots"\s+content="index[^"]*"\s*/?>', re.I)
CANONICAL = re.compile(r'<link\s+rel="canonical"', re.I)


def canonical_for(tree: str, rel_path: str) -> str:
    """The page's own absolute address, so the tag identifies one URL set."""
    return f"{BASE}{tree}/{rel_path}"


def repair(tree: str, root: Path) -> tuple[int, int]:
    """Return (pages_scanned, pages_changed). Every change is additive."""
    scanned = changed = 0
    for path in sorted(root.rglob("*.html")):
        scanned += 1
        rel = path.relative_to(root).as_posix()
        text = path.read_text(encoding="utf-8")
        original = text

        if HAS_ROBOTS.search(text):
            # Repair a tree that wrongly asked to be indexed; otherwise leave the
            # author's own directive exactly as written.
            text = INDEX_FOLLOW.sub(ROBOTS, text)
        elif "</head>" in text:
            inject = COMMENT + "\n" + ROBOTS + "\n"
            if not CANONICAL.search(text):
                inject += f'<link rel="canonical" href="{canonical_for(tree, rel)}">\n'
            text = text.replace("</head>", inject + "</head>", 1)

        if text != original:
            path.write_text(text, encoding="utf-8")
            changed += 1
    return scanned, changed


def main() -> int:
    total_scanned = total_changed = 0
    print(f"annex publication boundary — {BASE}\n")
    for tree, note in STATIC_TREES:
        root = ROOT / tree
        if not root.is_dir():
            print(f"  MISSING  {tree}/ ({note})", file=sys.stderr)
            return 1
        scanned, changed = repair(tree, root)
        total_scanned += scanned
        total_changed += changed
        print(f"  {tree + '/':24} {scanned:3} pages · {changed:3} repaired · {note}")
    print(f"\n{total_scanned} pages scanned, {total_changed} repaired.")
    if not total_changed:
        print("Nothing to do: every static annex page already declares a robots directive.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
