"""Build data/requirements.json — the root requirements register.

Every row records: the requirement as the brief states it, the status judged
against THIS repository on 2026-11-16, the files that implement it (checked to
exist by the build guard), and the official source that settles the blocking
question where one exists.

Status vocabulary is fixed at four values so a count is meaningful:
  delivered     — implemented and visible on the published site
  partial       — implemented in part; the gap is named on the row
  blocked       — cannot be done from outside Amazon's own systems
  not_delivered — buildable today, not built yet
"""
